/// A 3D colour table in `.cube` order: red changes fastest, then green, then
/// blue. Values are 8-bit RGB triples.
class ColorCube {
  ColorCube(this.size, this.rgb) {
    if (rgb.length != size * size * size * 3) {
      throw ArgumentError.value(rgb.length, 'rgb', 'must hold size³ triples');
    }
  }

  final int size;
  final Uint8List rgb;

  /// ARGB_8888 ints in `.cube` order, as Android's Media3 `SingleColorLut`
  /// and `Bitmap` expect after reshaping to `cube[r][g][b]`.
  Int32List toArgb() {
    final out = Int32List(size * size * size);
    for (var i = 0, j = 0; i < out.length; i++, j += 3) {
      out[i] = (0xFF << 24) | (rgb[j] << 16) | (rgb[j + 1] << 8) | rgb[j + 2];
    }
    return out;
  }

  /// The Adobe/Resolve `.cube` text form, usable by ffmpeg's `lut3d`, DaVinci
  /// Resolve, Final Cut Pro, Premiere, and LumaFusion.
  String toCubeText({String title = 'AquaRecover'}) {
    final safeTitle = title.replaceAll(RegExp(r'["\r\n]'), ' ');
    final buffer = StringBuffer()
      ..writeln('TITLE "$safeTitle"')
      ..writeln('# Generated by AquaRecover')
      ..writeln('LUT_3D_SIZE $size')
      ..writeln('DOMAIN_MIN 0.0 0.0 0.0')
      ..writeln('DOMAIN_MAX 1.0 1.0 1.0');
    String unit(int byte) => (byte / 255).toStringAsFixed(6);
    for (var j = 0; j < rgb.length; j += 3) {
      buffer
        ..write(unit(rgb[j]))
        ..write(' ')
        ..write(unit(rgb[j + 1]))
        ..write(' ')
        ..writeln(unit(rgb[j + 2]));
    }
    return buffer.toString();
  }

  Future<File> writeCube(String path, {String title = 'AquaRecover'}) =>
      File(path).writeAsString(toCubeText(title: title), flush: true);
}

/// Turns the AquaRecover colour restoration plus an optional creative LUT into
/// one [ColorCube] that GPU video pipelines without our shaders can apply.
///
/// Android (Media3 Transformer) and Windows (ffmpeg `lut3d`) export video this
/// way. Scene statistics come from a few sampled frames, so a clip is graded
/// consistently instead of flickering frame to frame.
class VideoLutBaker {
  const VideoLutBaker({
    this.processor = const UnderwaterProcessor(),
    this.lutService = const LutService(),
  });

  static const defaultSize = 33;
  static const sampleMaxDimension = 384;

  final UnderwaterProcessor processor;
  final LutService lutService;

  /// Bakes on a worker isolate from encoded (JPEG/PNG) frames.
  static Future<ColorCube> bakeFromEncodedFrames(
    List<Uint8List> frames,
    RestorationSettings settings, {
    LutProfile lutProfile = LutProfile.none,
    int size = defaultSize,
  }) async {
    final settingsJson = settings.toJson();
    final lutJson = lutProfile.toJson();
    final rgb = await Isolate.run(() async {
      final decoded = <img.Image>[];
      for (final bytes in frames) {
        final frame = img.decodeImage(bytes);
        if (frame != null) decoded.add(frame);
      }
      if (decoded.isEmpty) {
        throw const FormatException('No video frame could be decoded.');
      }
      final cube = await const VideoLutBaker().bake(
        decoded,
        RestorationSettings.fromJson(settingsJson),
        lutProfile: LutProfile.fromJson(lutJson),
        size: size,
      );
      return TransferableTypedData.fromList([cube.rgb]);
    }, debugName: 'AquaRecover LUT bake');
    return ColorCube(size, rgb.materialize().asUint8List());
  }

  Future<ColorCube> bake(
    List<img.Image> frames,
    RestorationSettings settings, {
    LutProfile lutProfile = LutProfile.none,
    int size = defaultSize,
  }) async {
    final lattice = processor.bakeColorLattice(
      sceneSample(frames),
      settings,
      size: size,
    );
    if (!lutProfile.isEnabled) return ColorCube(size, lattice);
    // Lattice pixel (x, y) is entry y * size + x, so the creative LUT, which
    // is a per-pixel colour map too, can run over it as an ordinary image.
    final image = img.Image.fromBytes(
      width: size,
      height: size * size,
      bytes: lattice.buffer,
      numChannels: 3,
    );
    final graded = await lutService.apply(image, lutProfile);
    final rgb = graded.convert(format: img.Format.uint8, numChannels: 3);
    return ColorCube(size, Uint8List.fromList(rgb.toUint8List()));
  }

  /// Stacks downscaled [frames] vertically so scene statistics weight every
  /// sampled moment of the clip equally.
  static img.Image sceneSample(List<img.Image> frames) {
    if (frames.isEmpty) {
      throw ArgumentError.value(frames, 'frames', 'must not be empty');
    }
    final scaled = [
      for (final frame in frames)
        frame.width > sampleMaxDimension || frame.height > sampleMaxDimension
            ? img.copyResize(
                frame,
                width: frame.width >= frame.height ? sampleMaxDimension : null,
                height: frame.height > frame.width ? sampleMaxDimension : null,
                interpolation: img.Interpolation.average,
              )
            : frame,
    ];
    if (scaled.length == 1) return scaled.single;
    final width = scaled.map((f) => f.width).reduce((a, b) => a > b ? a : b);
    final height = scaled.fold<int>(0, (sum, f) => sum + f.height);
    final sample = img.Image(width: width, height: height, numChannels: 4);
    var y = 0;
    for (final frame in scaled) {
      // Narrower frames are stretched to the full width so no padding colour
      // leaks into the statistics.
      final row = frame.width == width
          ? frame
          : img.copyResize(frame, width: width, height: frame.height);
      img.compositeImage(sample, row, dstY: y);
      y += frame.height;
    }
    return sample;
  }
}
